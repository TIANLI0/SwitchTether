//! Pure routing logic of the stream proxy (no I/O; fully unit-tested).
//!
//! Three parties: the HOST (VS Code extension / Codex Desktop), the AGENT
//! child process (`claude` in stream-json mode / `codex app-server`) and the
//! DESKTOP broker (SwitchTether, relaying the phone).
//!
//! Rules:
//! - Everything the host sends goes to the agent, except a reply to a request
//!   the desktop already answered (first answer wins → dropped).
//! - Everything the agent sends goes to the host, except replies to requests
//!   the desktop injected (desktop-only). Everything is mirrored to the desktop.
//! - The desktop may inject lines for the agent. Replies to agent→client
//!   requests are accepted only while still pending; then the host is told to
//!   dismiss its dialog (Claude: `control_cancel_request`; Codex: app-server
//!   emits `serverRequest/resolved` itself).

use std::collections::{HashMap, HashSet};

use serde_json::{json, Value};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Dialect {
    /// Claude Code `--input-format stream-json` control protocol.
    ClaudeStream,
    /// Codex app-server JSON-RPC (ids may be numbers or strings).
    JsonRpc,
}

/// Prefix of ids generated by SwitchTether for its own requests.
pub const CLAUDE_ID_PREFIX: &str = "st_";
pub const RPC_ID_PREFIX: &str = "st-";

#[derive(Debug, Default, PartialEq)]
pub struct Actions {
    pub to_agent: Vec<String>,
    pub to_host: Vec<String>,
    pub to_desktop: Vec<Value>,
}

pub struct Router {
    dialect: Dialect,
    /// Agent→client requests not answered yet (key = canonical id string).
    pending: HashSet<String>,
    /// Raw JSON lines of pending agent→client requests, for replay on desktop restart.
    pending_lines: HashMap<String, String>,
    /// Claude Code native session_id observed on stdout (for history preload on reattach).
    claude_session_id: Option<String>,
    /// Codex thread/started lines (thread_id -> synthetic thread/started JSON line) for reattach.
    codex_threads: HashMap<String, String>,
}

fn id_key(v: &Value) -> Option<String> {
    match v {
        Value::String(s) => Some(format!("s:{s}")),
        Value::Number(n) => Some(format!("n:{n}")),
        _ => None,
    }
}

impl Router {
    pub fn new(dialect: Dialect) -> Self {
        Self {
            dialect,
            pending: HashSet::new(),
            pending_lines: HashMap::new(),
            claude_session_id: None,
            codex_threads: HashMap::new(),
        }
    }

    pub fn claude_session_id(&self) -> Option<&str> {
        self.claude_session_id.as_deref()
    }

    /// Frames to replay to a newly-reconnected desktop broker so it recovers
    /// open Codex threads and any still-pending approval/question prompts.
    pub fn reconnect_frames(&self) -> Vec<Value> {
        let mut out = Vec::new();
        for line in self.codex_threads.values() {
            out.push(json!({ "t": "out", "line": line }));
        }
        for line in self.pending_lines.values() {
            out.push(json!({ "t": "out", "line": line }));
        }
        out
    }

    #[cfg(test)]
    pub fn pending_count(&self) -> usize {
        self.pending.len()
    }

    /// A request the agent sends to its client (approval, question …).
    fn agent_request_id(&self, v: &Value) -> Option<String> {
        match self.dialect {
            Dialect::ClaudeStream => (v.get("type").and_then(|t| t.as_str())
                == Some("control_request"))
            .then(|| v.get("request_id").and_then(id_key))
            .flatten(),
            Dialect::JsonRpc => (v.get("method").is_some())
                .then(|| v.get("id").and_then(id_key))
                .flatten(),
        }
    }

    /// A reply (from host or desktop) to an agent→client request.
    fn reply_id(&self, v: &Value) -> Option<String> {
        match self.dialect {
            Dialect::ClaudeStream => (v.get("type").and_then(|t| t.as_str())
                == Some("control_response"))
            .then(|| {
                v.get("response")
                    .and_then(|r| r.get("request_id"))
                    .and_then(id_key)
            })
            .flatten(),
            Dialect::JsonRpc => (v.get("method").is_none()
                && (v.get("result").is_some() || v.get("error").is_some()))
            .then(|| v.get("id").and_then(id_key))
            .flatten(),
        }
    }

    /// Whether an agent reply belongs to a request the desktop injected.
    fn is_desktop_reply(&self, v: &Value) -> bool {
        match self.dialect {
            Dialect::ClaudeStream => {
                v.get("type").and_then(|t| t.as_str()) == Some("control_response")
                    && v.get("response")
                        .and_then(|r| r.get("request_id"))
                        .and_then(|i| i.as_str())
                        .is_some_and(|i| i.starts_with(CLAUDE_ID_PREFIX))
            }
            Dialect::JsonRpc => {
                v.get("method").is_none()
                    && v.get("id")
                        .and_then(|i| i.as_str())
                        .is_some_and(|i| i.starts_with(RPC_ID_PREFIX))
            }
        }
    }

    pub fn on_host(&mut self, line: &str) -> Actions {
        let mut a = Actions::default();
        let parsed: Option<Value> = serde_json::from_str(line).ok();
        if let Some(v) = &parsed {
            if let Some(id) = self.reply_id(v) {
                self.pending_lines.remove(&id);
                if !self.pending.remove(&id) {
                    // Already answered from the phone: the agent must not see a second answer.
                    a.to_desktop
                        .push(json!({ "t": "dropped_host_reply", "line": line }));
                    return a;
                }
            }
        }
        a.to_agent.push(line.to_string());
        a.to_desktop.push(json!({ "t": "in", "line": line }));
        a
    }

    pub fn on_agent(&mut self, line: &str) -> Actions {
        let mut a = Actions::default();
        let parsed: Option<Value> = serde_json::from_str(line).ok();
        if let Some(v) = &parsed {
            if self.is_desktop_reply(v) {
                a.to_desktop.push(json!({ "t": "out", "line": line }));
                return a;
            }
            if let Some(id) = self.agent_request_id(v) {
                self.pending.insert(id.clone());
                self.pending_lines.insert(id, line.to_string());
            }
            match self.dialect {
                Dialect::ClaudeStream => {
                    if let Some(sid) = v
                        .get("session_id")
                        .or_else(|| v.get("sessionId"))
                        .and_then(|s| s.as_str())
                        .filter(|s| !s.is_empty())
                    {
                        self.claude_session_id = Some(sid.to_string());
                    }
                    // Claude may cancel its own request (e.g. after an interrupt).
                    if v.get("type").and_then(|t| t.as_str()) == Some("control_cancel_request") {
                        if let Some(id) = v.get("request_id").and_then(id_key) {
                            self.pending.remove(&id);
                            self.pending_lines.remove(&id);
                        }
                    }
                }
                Dialect::JsonRpc => {
                    if let Some(t) = v.pointer("/result/thread").or_else(|| {
                        (v.get("method").and_then(|m| m.as_str()) == Some("thread/started"))
                            .then(|| v.pointer("/params/thread"))
                            .flatten()
                    }) {
                        if let Some(tid) = t.get("id").and_then(|x| x.as_str()) {
                            self.codex_threads.insert(
                                tid.to_string(),
                                json!({ "method": "thread/started", "params": { "thread": t } })
                                    .to_string(),
                            );
                        }
                    }
                    if v.get("method").and_then(|m| m.as_str()) == Some("serverRequest/resolved") {
                        if let Some(id) = v.pointer("/params/requestId").and_then(id_key) {
                            self.pending.remove(&id);
                            self.pending_lines.remove(&id);
                        }
                    }
                }
            }
        }
        a.to_host.push(line.to_string());
        a.to_desktop.push(json!({ "t": "out", "line": line }));
        a
    }

    pub fn on_desktop(&mut self, line: &str) -> Actions {
        let mut a = Actions::default();
        let Ok(v) = serde_json::from_str::<Value>(line) else {
            a.to_desktop
                .push(json!({ "t": "rejected", "reason": "invalid json" }));
            return a;
        };
        if let Some(id) = self.reply_id(&v) {
            self.pending_lines.remove(&id);
            if !self.pending.remove(&id) {
                a.to_desktop
                    .push(json!({ "t": "rejected", "reason": "already_answered", "line": line }));
                return a;
            }
            a.to_agent.push(line.to_string());
            if self.dialect == Dialect::ClaudeStream {
                if let Some(rid) = v.get("response").and_then(|r| r.get("request_id")) {
                    // Dismiss the dialog in the IDE.
                    a.to_host.push(
                        json!({ "type": "control_cancel_request", "request_id": rid }).to_string(),
                    );
                }
            }
            a.to_desktop.push(json!({ "t": "accepted", "line": line }));
            return a;
        }
        a.to_agent.push(line.to_string());
        a
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn claude_first_answer_wins_phone_first() {
        let mut r = Router::new(Dialect::ClaudeStream);
        let req =
            r#"{"type":"control_request","request_id":"r1","request":{"subtype":"can_use_tool"}}"#;
        let a = r.on_agent(req);
        assert_eq!(a.to_host, vec![req.to_string()]);
        assert_eq!(r.pending_count(), 1);
        let phone = r#"{"type":"control_response","response":{"subtype":"success","request_id":"r1","response":{"behavior":"allow"}}}"#;
        let a = r.on_desktop(phone);
        assert_eq!(a.to_agent, vec![phone.to_string()]);
        assert!(a.to_host[0].contains("control_cancel_request"));
        // the IDE answers late → dropped
        let ide = r#"{"type":"control_response","response":{"subtype":"success","request_id":"r1","response":{"behavior":"deny"}}}"#;
        let a = r.on_host(ide);
        assert!(a.to_agent.is_empty());
    }

    #[test]
    fn claude_first_answer_wins_ide_first() {
        let mut r = Router::new(Dialect::ClaudeStream);
        r.on_agent(r#"{"type":"control_request","request_id":"r2","request":{}}"#);
        let ide =
            r#"{"type":"control_response","response":{"request_id":"r2","subtype":"success"}}"#;
        assert_eq!(r.on_host(ide).to_agent.len(), 1);
        let a = r.on_desktop(ide);
        assert!(a.to_agent.is_empty());
        assert_eq!(a.to_desktop[0]["t"], "rejected");
    }

    #[test]
    fn claude_desktop_requests_and_messages() {
        let mut r = Router::new(Dialect::ClaudeStream);
        let msg = r#"{"type":"user","message":{"role":"user","content":"hi"}}"#;
        assert_eq!(r.on_desktop(msg).to_agent, vec![msg.to_string()]);
        let resp =
            r#"{"type":"control_response","response":{"subtype":"success","request_id":"st_5"}}"#;
        let a = r.on_agent(resp);
        assert!(
            a.to_host.is_empty(),
            "desktop's own replies never reach the IDE"
        );
        assert_eq!(a.to_desktop[0]["t"], "out");
        // normal output goes everywhere
        let out = r#"{"type":"assistant","message":{}}"#;
        let a = r.on_agent(out);
        assert_eq!(a.to_host.len(), 1);
        assert_eq!(a.to_desktop.len(), 1);
    }

    #[test]
    fn jsonrpc_routing() {
        let mut r = Router::new(Dialect::JsonRpc);
        // host request passes through and is mirrored
        let a = r.on_host(r#"{"id":1,"method":"thread/start","params":{}}"#);
        assert_eq!(a.to_agent.len(), 1);
        // server reply to host request goes to host
        let a = r.on_agent(r#"{"id":1,"result":{}}"#);
        assert_eq!(a.to_host.len(), 1);
        // server→client approval request
        r.on_agent(r#"{"id":0,"method":"item/commandExecution/requestApproval","params":{}}"#);
        assert_eq!(r.pending_count(), 1);
        let phone = r#"{"id":0,"result":{"decision":"accept"}}"#;
        let a = r.on_desktop(phone);
        assert_eq!(a.to_agent, vec![phone.to_string()]);
        assert!(a.to_host.is_empty());
        // second answer from the desktop is rejected
        assert_eq!(r.on_desktop(phone).to_desktop[0]["t"], "rejected");
        // the host answering the same approval later is dropped
        assert!(r
            .on_host(r#"{"id":0,"result":{"decision":"decline"}}"#)
            .to_agent
            .is_empty());
        // desktop's own request reply is desktop-only
        let a = r.on_agent(r#"{"id":"st-1","result":{}}"#);
        assert!(a.to_host.is_empty());
        // notifications go everywhere
        let a = r.on_agent(r#"{"method":"turn/started","params":{}}"#);
        assert_eq!((a.to_host.len(), a.to_desktop.len()), (1, 1));
    }

    #[test]
    fn non_json_lines_pass_through() {
        let mut r = Router::new(Dialect::ClaudeStream);
        assert_eq!(r.on_host("garbage").to_agent, vec!["garbage".to_string()]);
        assert_eq!(r.on_agent("garbage").to_host, vec!["garbage".to_string()]);
    }

    #[test]
    fn reconnect_frames_preserve_pending_requests_and_threads() {
        let mut r = Router::new(Dialect::JsonRpc);
        r.on_agent(r#"{"method":"thread/started","params":{"thread":{"id":"th1","cwd":"/p"}}}"#);
        r.on_agent(r#"{"id":7,"method":"item/tool/requestUserInput","params":{"threadId":"th1"}}"#);
        let frames = r.reconnect_frames();
        assert_eq!(frames.len(), 2);
        // Once answered, pending request is no longer replayed.
        r.on_desktop(r#"{"id":7,"result":{"answers":{}}}"#);
        assert_eq!(r.reconnect_frames().len(), 1);
    }
}
